#!/usr/bin/env python3
"""Mirror GitHub issues into .scratch/issues/ as markdown (one-way, GitHub wins).

Usage: python3 scripts/sync_issues.py [--repo owner/name] [--out DIR]
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRIAGE = ["needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "wontfix"]
FIELDS = "number,title,body,labels,state,comments,url,author,createdAt"
MARK = "<!-- generated by scripts/sync_issues.py; edit on GitHub, not here -->"


def slug(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:50] or "issue"


def render(issue):
    labels = [l["name"] for l in issue["labels"]]
    status = "closed" if issue["state"] == "CLOSED" else next(
        (l for l in labels if l in TRIAGE), "untriaged")
    lines = [
        MARK,
        f"# #{issue['number']} {issue['title']}",
        "",
        f"Status: {status}",
        f"Labels: {', '.join(labels) or '-'}",
        f"Author: {issue['author']['login']} | Created: {issue['createdAt'][:10]}",
        f"URL: {issue['url']}",
        "",
        (issue["body"] or "").strip(),
    ]
    if issue["comments"]:
        lines += ["", "## Comments"]
        for c in issue["comments"]:
            lines += ["", f"**{c['author']['login']}** ({c['createdAt'][:10]}):", "", c["body"].strip()]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", help="owner/name; default: inferred from git remote")
    ap.add_argument("--out", type=Path, default=ROOT / ".scratch" / "issues")
    args = ap.parse_args()

    # ponytail: 1000-issue cap, paginate via `gh api` if the repo outgrows it
    cmd = ["gh", "issue", "list", "--state", "all", "--limit", "1000", "--json", FIELDS]
    if args.repo:
        cmd += ["--repo", args.repo]
    issues = json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True, cwd=ROOT).stdout)

    args.out.mkdir(parents=True, exist_ok=True)
    keep = set()
    for issue in issues:
        path = args.out / f"{issue['number']:04d}-{slug(issue['title'])}.md"
        path.write_text(render(issue))
        keep.add(path)
    # drop files for renamed/deleted issues, only ones this script generated
    for stale in set(args.out.glob("*.md")) - keep:
        if stale.read_text().startswith(MARK):
            stale.unlink()
    print(f"synced {len(issues)} issues -> {args.out}")


if __name__ == "__main__":
    main()
